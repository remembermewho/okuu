// «Оплата получена … за кого»: склоняем только когда уверены; иначе — без склонения.
func TestAccusativeRU(t *testing.T) {
	tests := []struct {
		in, want string // want "" — не склоняем
	}{
		{"Айдана Токтосунова", "Айдану Токтосунову"},
		{"Токтосунова Айдана", "Токтосунову Айдану"},
		{"София Токтосунова", "Софию Токтосунову"},
		{"Бекжан Токтосунов", "Бекжана Токтосунова"},
		{"Асанов Бекзат", "Асанова Бекзата"},
		{"Сыдыков Арген", "Сыдыкова Аргена"},
		{"Асель Токтосунова", "Асель Токтосунову"},
		{"Айгерим Асанова", "Айгерим Асанову"},
		{"Карина Ким", "Карину Ким"},
		{"Никита Иванов", "Никиту Иванова"},
		{"Илья Петров", "Илью Петрова"},
		{"Игорь Смирнов", "Игоря Смирнова"},
		{"Дмитрий Ковальский", "Дмитрия Ковальского"},
		{"Анна Ковальская", "Анну Ковальскую"},
		{"Андрей Шевченков", "Андрея Шевченкова"},
		{"Павел Петров", "Павла Петрова"},
		{"Андрей Шевченко", ""}, // фамилия не говорит о поле
		{"Павел Черных", ""},
		{"Бекжан Асан уулу", "Бекжана Асан уулу"},
		{"Айдана Асан кызы", "Айдану Асан кызы"},
		{"Айдана Бакытовна Токтосунова", "Айдану Бакытовну Токтосунову"},
		{"АЙДАНА ТОКТОСУНОВА", "АЙДАНУ ТОКТОСУНОВУ"},
		{"Айдана", "Айдану"},
		{"Рая Петрова", "Раю Петрову"},
		// Пол не понять или не кириллица — без склонения.
		{"Бакыт Ким", ""},
		{"Бекжан", ""},
		{"Анна-Мария Петрова", ""},
		{"John Smith", ""},
		{"Карина Асанов", ""}, // противоречие
		{"Лев Толстой", ""},
		{"", ""},
	}
	for _, tt := range tests {
		got, ok := AccusativeRU(tt.in)
		if tt.want == "" {
			if ok {
				t.Errorf("%q → %q, want без склонения", tt.in, got)
			}
			continue
		}
		if !ok || got != tt.want {
			t.Errorf("%q → %q (%v), want %q", tt.in, got, ok, tt.want)
		}
	}
}

// Напоминание: сначала просроченные (дольше — выше), затем ожидающие по сроку; «срок сегодня», «срок до».
func TestDebtReminderOrder(t *testing.T) {
	d := func(s string) *civil.Date {
		v, err := civil.Parse(s)
		if err != nil {
			t.Fatal(err)
		}
		return &v
	}
	text := DebtReminder(ru, KindManual, "Билим", *d("2026-11-02"), []ChildDebt{
		{Name: "Азамат", Debt: 100_000, Due: d("2026-11-05")},
		{Name: "Бакыт", Debt: 200_000, Due: d("2026-11-02"), DueToday: true},
		{Name: "Вика", Debt: 150_000, Due: d("2026-11-01"), DaysOverdue: 1},
		{Name: "Гуля", Debt: 50_000, Due: d("2026-10-20"), DaysOverdue: 13},
	}, "")
	want := "• Гуля — 500 сом, просрочено на 13 дней\n• Вика — 1 500 сом, просрочено на 1 день\n" +
		"• Бакыт — 2 000 сом, срок сегодня\n• Азамат — 1 000 сом, срок до 05.11\nИтого: 5 000 сом"
	if !strings.Contains(text, want) {
		t.Errorf("напоминание:\n%s", text)
	}
}

// «Оплата получена» без склонения, если имя не склоняется уверенно.
func TestPaidFallback(t *testing.T) {
	got := ru.Paid("Билим", "Бакыт Ким", 150_000, 0, nil)
	if got != "🏫 Центр «Билим»\nОплата получена: 1 500 сом — Бакыт Ким. Спасибо!\nБаланс: 0 сом, долгов нет" {
		t.Errorf("Paid = %q", got)
	}
}
